// Witness runs (pli check, PR 3; the owner's decisions at Phase A): every
// finding with a witness carries it as a story, in the story grammar of
// internal/story, so that it can be run against the real kernel. A
// witness run is generated, so it is not a story in V5's sense: it is
// never saved under stories/, its author line says it was generated, and
// it expects no timeline (expect: []). Running it checks only what its
// steps do: each is accepted (run_test.go).
//
// How a witness becomes a story, the rules these texts pin:
//   - The people: ana is the requester, dee a colleague, bot the agent,
//     kai whoever made the container, and the person a principal field
//     names is called after the field (f_manager: manager). Each holds
//     the role its class holds in the witness. People are in name order.
//   - The Item is item, its container container. A container is made in
//     given, by kai, of the first Type the start block names, at its
//     latest version; an Item whose start block names none is made at the
//     top level.
//   - Steps start at day 1 09:00, one minute apart. A reaction's step is
//     no step: the kernel makes it.
//   - Values, in the Type's field order: a create gives the fields its
//     state's invariants need, and the fields the path's guards read that
//     no move gives; a move gives its required fields; a colleague's
//     write gives the fields the finding lists; a claim gives the mover.
//     Each is the first sample of its type: "x", 0, the first option,
//     true, day 1, day 1 09:00, or the person.
//   - A fake for every action the hooks of the Types it makes call (and
//     of those their reactions make), in action order: a check answers
//     with each output corrected to a sample (allow when it has none);
//     an enrich or an action answers ok with each output a sample.
package check_test

