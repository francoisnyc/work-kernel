func stories(t *testing.T, dir string) check.Report {
	t.Helper()
	return check.CheckStories(loadDir(t, dir), contracts.Default())
}

// finding returns the one finding of r with this Type version, code and
// path.
func finding(t *testing.T, r check.Report, id string, version int, code check.Code, path string) check.Finding {
	t.Helper()
	var out []check.Finding
	for _, f := range of(r, id, version) {
		if f.Code == code && f.Path == path {
			out = append(out, f)
		}
	}
	if len(out) != 1 {
		t.Fatalf("%s@%d %s %s: %d findings, want 1", id, version, code, path, len(out))
	}
	return out[0]
}

// parseStory holds a witness run's text to the story grammar and to the
// folder's Types and contracts, as story.Run would.
func parseStory(t *testing.T, dir, text string) *story.Story {
	t.Helper()
	s, err := story.Parse("witness run", []byte(text))
	if err != nil {
		t.Fatalf("the witness run does not parse: %v\n%s", err, text)
	}
	if p := story.Check(s, loadDir(t, dir), contracts.Default()); len(p) > 0 {
		t.Fatalf("the witness run does not check: %v\n%s", p, text)
	}
	return s
}

func TestStoryTexts(t *testing.T) {
	for _, c := range []struct {
		dir, id string
		version int
		code    check.Code
		path    string
		want    string
	}{
		{typesDir, "incident", 7, check.CodeAgentDecides, "transitions[8]", wantIncidentStory},
		{typesDir, "access_request", 2, check.CodeColleagueEditsDraft, "states[0]", wantDraftStory},
		{camundaDir, "purchase", 1, check.CodeAgentDecides, "transitions[6]", wantPurchaseStory},
	} {
		t.Run(c.id, func(t *testing.T) {
			// The expected text is a story the runner reads.
			parseStory(t, c.dir, c.want)
			f := finding(t, stories(t, c.dir), c.id, c.version, c.code, c.path)
			if f.Story != c.want {
				t.Errorf("%s@%d %s %s, the witness run:\n got:\n%s\nwant:\n%s", c.id, c.version, c.code, c.path, f.Story, c.want)
			}
		})
	}
}

// Every finding with a witness has a witness run that parses and checks;
// a dead rule, which has none, has no story. Check, unlike CheckStories,
// writes none: its findings are as before.
func TestEveryWitnessIsAStory(t *testing.T) {
	for _, dir := range []string{typesDir, camundaDir, camundaV2Dir, blindDir, staffRoleDir} {
		r := stories(t, dir)
		n := 0
		for _, f := range r.Findings {
			if len(f.Witness) == 0 {
				if f.Story != "" {
					t.Errorf("%s@%d %s %s has no witness but a story:\n%s", f.Type, f.Version, f.Code, f.Path, f.Story)
				}
				continue
			}
			n++
			if f.Story == "" {
				t.Errorf("%s@%d %s %s: no witness run", f.Type, f.Version, f.Code, f.Path)
				continue
			}
			parseStory(t, dir, f.Story)
		}
		if n == 0 {
			t.Errorf("%s: no finding with a witness", dir)
		}
		for _, f := range runDir(t, dir).Findings {
			if f.Story != "" {
				t.Errorf("Check wrote a story on %s@%d %s %s", f.Type, f.Version, f.Code, f.Path)
			}
		}
	}
	for _, f := range check.CheckStories([]*typedef.Type{parse(t, deadType)}, contracts.Default()).Findings {
		if f.Story != "" {
			t.Errorf("t_dead %s %s, a dead rule, has a story:\n%s", f.Code, f.Path, f.Story)
		}
	}
}

// The text of a report CheckStories made prints each witness run under
// its witness, indented, and says of a dead rule that it has none. Check's
// text is as before.
func TestTextWithStories(t *testing.T) {
	text := stories(t, camundaDir).Text()
	var block strings.Builder
	block.WriteString("    5. An agent holding finance moves it from finance_review to approved.\n    Witness run:\n")
	for _, line := range strings.SplitAfter(strings.TrimSuffix(wantPurchaseStory, "\n"), "\n") {
		block.WriteString("      " + line)
	}
	block.WriteString("\n")
	if !strings.Contains(text, block.String()) {
		t.Errorf("the text lacks the witness run under the witness:\n%s\nin:\n%s", block.String(), text)
	}
	if strings.Contains(runDir(t, camundaDir).Text(), "Witness run") {
		t.Errorf("Check's text prints witness runs")
	}
	dead := check.CheckStories([]*typedef.Type{parse(t, deadType)}, contracts.Default()).Text()
	want := "  UNREACHABLE_STATE ERROR states[3]: No Item can ever be in island: nothing leads there, whoever holds which role and whatever the guards say.\n    No witness run: it can never happen.\n"
	if !strings.Contains(dead, want) {
		t.Errorf("the dead rule's text lacks\n%s\nin:\n%s", want, dead)
	}
}
