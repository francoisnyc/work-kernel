"""Measure 2, kernel side: "over 5,000, the CFO too", with requests in flight
at each step. The change is the first bake-off's purchase@2
(spikes/camunda-bakeoff/kernel/types-v2/), put live by restarting the item
service with that folder. Writes results/change-kernel.md.
"""
import os
import subprocess
import time

from pt import FIRST, SPIKE, pli, short

out = ["# Measure 2, kernel: the CFO change with requests in flight\n",
       f"Generated by scripts/test_change_kernel.py on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}.\n"]


def say(s):
    print(s)
    out.append(s)


def new(version, to):
    _, c = pli("ana", "item", "create", "--type", f"purchase@{version}", "--set", "f_amount=6000", "--set", "f_vendor=cloudhost",
               "--set", "f_cost_centre=CC-100", "--set", "f_justification=Three servers")
    i = short(c["item"]["name"])
    pli("ana", "item", "transition", i, "--to", "manager_review", "--wait", "5s")
    if to in ("finance_queue", "finance_review", "approved"):
        pli("bob", "item", "transition", i, "--to", "finance_queue")
    if to in ("finance_review", "approved"):
        pli("fay", "item", "transition", i, "--to", "finance_review", "--set", "f_claimed_by=user:fay")
    if to == "approved":
        pli("fay", "item", "transition", i, "--to", "approved")
    return i


def finish(i):
    """Drive a purchase to finance's approval from wherever it stands; say where it ends."""
    _, it = pli("fay", "item", "get", i)
    st = it["item"]["state"]
    if st == "manager_review":
        pli("bob", "item", "transition", i, "--to", "finance_queue")
        st = "finance_queue"
    if st == "finance_queue":
        pli("fay", "item", "transition", i, "--to", "finance_review", "--set", "f_claimed_by=user:fay")
    ok, res = pli("fay", "item", "transition", i, "--to", "approved", check=False)
    if ok:
        return "approved by finance, no CFO"
    _, res = pli("fay", "item", "transition", i, "--to", "cfo_review")
    return f"finance's approval sent it to {res['item']['state']}"


steps = ["manager_review", "finance_queue", "finance_review", "approved"]
before = {s: new(1, s) for s in steps}
say("- Before the change, four 6,000 purchases on purchase@1, one at each step: " + ", ".join(steps) + ".")
t0 = time.time()
subprocess.run([f"{FIRST}/scripts/kernel-restart-itemservice.sh", f"{FIRST}/kernel/types-v2"], check=True, capture_output=True)
say(f"- The change put live: the item service restarted with purchase@2 registered beside purchase@1 ({time.time() - t0:.1f} s; "
    "11 lines of YAML added, 3 changed: spikes/camunda-bakeoff/results/test1-kernel-purchase-v1-v2.diff).")
# Since track 1, item 6, step 2 an administrator can migrate a request in flight to the new version, once the kernel has checked that it fits.
moved = 0
for s in steps[:3]:
    _, dry = pli("ivy", "item", "migrate", before[s], "--to", "purchase@2", "--dry-run")
    ok, res = pli("ivy", "item", "migrate", before[s], "--to", "purchase@2", check=False)
    if ok:
        moved += 1
        say(f"- In flight at {s}: an administrator migrated it to purchase@2 (the dry run found {len(dry.get('problems', []))} problems); {finish(before[s])}.")
    else:
        say(f"- In flight at {s}: the migrate was refused ({' '.join(str(res).split())[:160]}); {finish(before[s])} (it keeps purchase@1).")
_, it = pli("fay", "item", "get", before["approved"])
say(f"- Already approved: still `{it['item']['state']}`, readable as before; its version's rules are kept with it.")
say(f"- A new purchase@2: {finish(new(2, 'manager_review'))}.")
# Since track 1, item 6, step 1 the kernel refuses this create; the row records the refusal (it used to run the purchase to its end).
ok, res = pli("ana", "item", "create", "--type", "purchase@1", "--set", "f_amount=6000", "--set", "f_vendor=cloudhost",
              "--set", "f_cost_centre=CC-100", "--set", "f_justification=Three servers", check=False)
say("- A new purchase asked for on the OLD version by name (purchase@1), after the change: "
    + ("created (the first bake-off's gap: a creator may pick any registered version)." if ok
       else "refused: " + " ".join(str(res).split())[:200]))
ok, res = pli("ivy", "item", "migrate", before["approved"], "--to", "purchase@2", check=False)
say("- The one already approved: " + ("migrated" if ok else "not migrated (" + " ".join(str(res).split())[:160] + ")") + ".")
say(f"- The change reached {moved} of the 3 requests in flight, each by one checked migrate; a fan of them at once is a later step.")
open(os.path.join(SPIKE, "results/change-kernel.md"), "w").write("\n".join(out) + "\n")
