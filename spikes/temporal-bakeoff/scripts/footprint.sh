#!/usr/bin/env bash
# Footprint of each side: scripts/footprint.sh LABEL (appends to results/footprint.md).
cd "$(dirname "$0")/.."
FIRST=../camunda-bakeoff
OUT=results/footprint.md
[ -f "$OUT" ] || printf '# Footprint\n\nGenerated by scripts/footprint.sh. Memory as docker stats (containers) and ps RSS (programs on the host). The shared stubs are on neither side.\n' > "$OUT"
{
  echo; echo "## ${1:-snapshot} ($(date -u '+%Y-%m-%d %H:%M UTC'))"; echo
  echo "| Side | Part | Memory |"; echo "|---|---|---|"
  docker stats --no-stream --format '{{.Name}}|{{.MemUsage}}' | sort | while IFS='|' read -r n m; do
    case $n in bakeoff-kernel-*) s=kernel;; bakeoff2-plain-*) s=plain;; *) continue;; esac
    echo "| $s | container $n | ${m%% /*} |"
  done
  for p in itemservice relay worker; do
    [ -f $FIRST/.run/$p.pid ] && rss=$(ps -o rss= -p "$(cat $FIRST/.run/$p.pid)" 2>/dev/null) && echo "| kernel | process $p | $((rss / 1024))MiB |"
  done
  [ -f .run/ptapp.pid ] && rss=$(ps -o rss= -p "$(cat .run/ptapp.pid)" 2>/dev/null) && echo "| plain | process ptapp (API and worker) | $((rss / 1024))MiB |"
  echo; echo "Programs on disk: kernel $(du -ch $FIRST/.bin/itemservice $FIRST/.bin/relay $FIRST/.bin/worker 2>/dev/null | tail -1 | cut -f1), plain $(du -h .bin/ptapp 2>/dev/null | cut -f1)."
} >> "$OUT"
tail -14 "$OUT"
