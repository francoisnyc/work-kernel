"""Measure 2, plain Temporal: "over 5,000, the CFO too", with requests in
flight at each step. The program is started as it was before the change,
requests are put at each step, and the change is then deployed twice over
the same recorded histories: carelessly (no versioning), and the way
Temporal documents (workflow.GetVersion). Writes results/change-plain.md.

Run on a fresh plain side started with PURCHASE_CODE=before.
"""
import os
import subprocess
import time

from pt import SPIKE, plain, wait_state

out = ["# Measure 2, plain Temporal: the CFO change with requests in flight\n",
       f"Generated by scripts/test_change_plain.py on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}.\n"]


def say(s):
    print(s)
    out.append(s)


def new(to, amount=6000):
    _, r = plain("ana", "POST", "/purchases", {"amount": amount, "vendor": "cloudhost", "cost_centre": "CC-100", "justification": "Three servers"})
    rid = r["id"]
    wait_state("ana", rid, "manager_review")
    if to in ("finance_queue", "finance_review", "approved"):
        plain("bob", "POST", f"/purchases/{rid}/decision", {"approve": True})
    if to in ("finance_review", "approved"):
        plain("fay", "POST", f"/purchases/{rid}/claim")
    if to == "approved":
        plain("fay", "POST", f"/purchases/{rid}/decision", {"approve": True})
        wait_state("ana", rid, "approved")
    return rid


def finish(rid):
    """Drive a purchase to finance's approval from wherever it stands; say where it goes."""
    _, row = plain("fay", "GET", f"/requests/{rid}")
    st = row["data"]["state"]
    if st == "manager_review":
        plain("bob", "POST", f"/purchases/{rid}/decision", {"approve": True})
        st = "finance_queue"
    if st == "finance_queue":
        plain("fay", "POST", f"/purchases/{rid}/claim")
    plain("fay", "POST", f"/purchases/{rid}/decision", {"approve": True})
    return wait_state("ana", rid, "cfo_review", "approved")["data"]["state"]


def replay(mode):
    r = subprocess.run([f"{SPIKE}/.bin/ptreplay", "--purchase-code", mode], capture_output=True, text=True)
    return r.returncode, r.stdout.strip().splitlines()


def deploy(mode):
    subprocess.run([f"{SPIKE}/scripts/plain-restart.sh", mode], check=True, capture_output=True)


steps = ["manager_review", "finance_queue", "finance_review", "approved"]
before = {s: new(s) for s in steps}
time.sleep(2)
say("- Before the change, four 6,000 purchases, one at each step: " + ", ".join(steps) + ".")

say("\n## The change made carelessly (the new branch added, no versioning)\n")
code, lines = replay("naive")
say(f"- Temporal's replay check of the recorded histories against the changed code (`ptreplay`): exit {code}; {lines[-1]}")
for l in lines[:-1]:
    if "DOES NOT REPLAY" in l:
        say(f"  - `{l[:330]}`")
deploy("naive")
st, body = plain("ana", "GET", f"/requests/{before['approved']}")
say(f"- Deployed anyway: reading the purchase approved before the change now answers HTTP {st} {str(body)[:120]} "
    "(its history can no longer be replayed, so its state cannot be asked for).")

say("\n## The change made as Temporal documents (workflow.GetVersion)\n")
code, lines = replay("patched")
say(f"- The replay check: exit {code}; {lines[-1]}")
deploy("patched")
st, body = plain("ana", "GET", f"/requests/{before['approved']}")
say(f"- Deployed: the purchase approved before the change reads HTTP {st}, state `{body.get('data', {}).get('state')}`, order `{body.get('data', {}).get('order_id')}`.")
for s in steps[:3]:
    end = finish(before[s])
    say(f"- In flight at {s} when the change was deployed: after finance's approval it is in `{end}`"
        + (": the change reached it." if end == "cfo_review" else "."))
rid = before["finance_review"]
for who in ("fay", "prep-bot"):
    st, body = plain(who, "POST", f"/purchases/{rid}/decision", {"approve": True})
    say(f"- {who} tries the CFO's step: HTTP {st} {body.get('error', body) if isinstance(body, dict) else body}")
st, _ = plain("cora", "POST", f"/purchases/{rid}/decision", {"approve": True})
row = wait_state("ana", rid, "approved")
time.sleep(1.5)
_, row = plain("ana", "GET", f"/requests/{rid}")
say(f"- cora (cfo) approves: HTTP {st}; state `{row['data']['state']}`, order `{row['data'].get('order_id')}`; "
    f"cora's inbox still holds {len(plain('cora', 'GET', '/inbox')[1]['requests'])} waiting on the CFO.")
say(f"- A new 6,000 purchase: after finance, `{finish(new('manager_review'))}`. A new 2,500 purchase: after finance, `{finish(new('manager_review', 2500))}`.")
say("- Where the change applies is where the developer put the version check. Here it sits at finance's approval, so every request "
    "that had not yet passed it took the CFO step; put at the start of the workflow instead, requests in flight would have kept the old rule.")
open(os.path.join(SPIKE, "results/change-plain.md"), "w").write("\n".join(out) + "\n")
