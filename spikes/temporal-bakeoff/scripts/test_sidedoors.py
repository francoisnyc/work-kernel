"""Side doors on both sides: no credentials at all, or the development
defaults. Not the agent's credentials: what a compromised agent reaches if
it runs on the same machine or network. Writes results/sidedoors.md.

The kernel's forged workflow start is the first bake-off's known hole
(docs/research/camunda-bakeoff.md, test 2c); its fix ("an effect re-checks
committed state") was not on main when this ran. It is reported here beside
plain Temporal's equivalent, and the report does not let it decide.
"""
import json
import os
import subprocess
import time
import urllib.error
import urllib.request

from pt import SPIKE, plain, pli, short, wait_state

out = ["# Side doors: no credentials, or the development defaults\n",
       f"Generated by scripts/test_sidedoors.py on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}.\n",
       "| Side | Door | Result | Evidence |", "|---|---|---|---|"]


def row(side, door, label, evidence):
    line = f"| {side} | {door} | {label} | {' '.join(str(evidence).split())[:300]} |"
    print(line)
    out.append(line)


def temporal(container, *args):
    return subprocess.run(["docker", "exec", container, "temporal", *args, "--address", "localhost:7233"], capture_output=True, text=True)


def psql(dsn, sql):
    return subprocess.run(["psql", dsn, "-Atc", sql], capture_output=True, text=True)


# ------------------------------------------------------------ plain Temporal
st, body = plain(None, "GET", "/inbox")
row("plain", "its API without a token", "closed" if st == 401 else "OPEN", f"HTTP {st} {body}")

# Temporal's development server has no sign-on. Send the manager's decision
# straight to a purchase's workflow, saying it comes from the manager.
_, r = plain("ana", "POST", "/purchases", {"amount": 500, "vendor": "officeco", "cost_centre": "CC-100", "justification": "Side door"})
rid = r["id"]
wait_state("ana", rid, "manager_review")
t = temporal("bakeoff2-plain-temporal-1", "workflow", "update", "execute", "--workflow-id", rid, "--name", "decide",
             "--input", json.dumps({"actor": {"id": "user:bob"}, "approve": True}))
time.sleep(3)
_, got = plain("ana", "GET", f"/requests/{rid}")
d = got.get("data", {})
row("plain", "Temporal (development server, no sign-on): send the manager's approval straight to the workflow, naming the manager",
    "OPEN" if d.get("order_id") else "closed",
    f"update exit {t.returncode}; the purchase is {d.get('state')} and the purchase system {'received order ' + d['order_id'] if d.get('order_id') else 'received nothing'}; "
    f"the audit trail says: {[(e['actor'], e['action']) for e in plain('ana', 'GET', f'/requests/{rid}/history')[1].get('events', [])]}")

# Postgres holds only the inbox's copy. Change the amount there.
PLAIN_DSN = "postgres://plain:plain@127.0.0.1:25432/plain"
_, r = plain("ana", "POST", "/purchases", {"amount": 2500, "vendor": "officeco", "cost_centre": "CC-100", "justification": "Side door"})
rid = r["id"]
wait_state("ana", rid, "manager_review")
p = psql(PLAIN_DSN, f"update requests set data = jsonb_set(data, '{{amount}}', '1'), readers = readers || '{{agent:prep-bot,user:olaf}}' where id = '{rid}' returning id")
_, inbox = plain("bob", "GET", "/inbox")
shown = next((x["data"].get("amount") for x in inbox.get("requests", []) if x["id"] == rid), None)
_, truth = plain("bob", "GET", f"/requests/{rid}")
stranger = plain("olaf", "GET", f"/requests/{rid}")[0]  # before the workflow next rewrites its row
plain("bob", "POST", f"/purchases/{rid}/decision", {"approve": True})
after = wait_state("ana", rid, "finance_queue", "approved")
row("plain", "Postgres with the development password: change a waiting purchase's amount to 1",
    "misleads the inbox and who may read; decides nothing",
    f"psql exit {p.returncode}; the manager's inbox now shows amount {shown}; the request itself (read from the workflow) says {truth.get('data', {}).get('amount')}; "
    f"approved by the manager it went to {after.get('state')} (2,500 needs finance): the workflow kept the truth. "
    f"The same write named olaf, a stranger to it, as a reader: his read answered HTTP {stranger} "
    "(who may see a request is decided from the copy in Postgres), until the workflow's next write put the row back.")

# ------------------------------------------------------------ kernel
def http(url, body):
    req = urllib.request.Request(url, method="POST", data=json.dumps(body).encode(), headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            return r.status, r.read()[:160].decode(errors="replace")
    except urllib.error.HTTPError as e:
        return e.code, e.read()[:160].decode(errors="replace")


st, body = http("http://127.0.0.1:18080/kernel.v1.ItemService/SearchItems", {"parent": "namespaces/acme", "query": "x"})
row("kernel", "its API without a token", "closed" if st == 401 else "OPEN", f"HTTP {st} {body}")

_, c = pli("ana", "item", "create", "--type", "purchase@1", "--set", "f_amount=500", "--set", "f_vendor=officeco",
           "--set", "f_cost_centre=CC-100", "--set", "f_justification=Side door")
i = short(c["item"]["name"])
pli("ana", "item", "transition", i, "--to", "manager_review", "--wait", "5s")
payload = {"ItemID": i, "Carried": {"TypeID": "purchase", "TypeVersion": 1, "State": "approved", "LastAppliedSeq": 999,
                                    "EnteredSeq": 3, "PendingActions": [{"HookID": "place_order", "CauseSeq": 3}]}}
t = temporal("bakeoff-kernel-temporal-1", "workflow", "start", "--type", "item", "--task-queue", "items",
             "--workflow-id", f"sidedoor-{int(time.time())}", "--input", json.dumps(payload))
time.sleep(5)
_, it = pli("bob", "item", "get", i)
order = it["item"]["fields"].get("f_order_id")
row("kernel", "Temporal (development server, no sign-on): start the kernel's workflow claiming the purchase is approved (the first bake-off's known hole)",
    "OPEN (known)" if order else "closed",
    f"workflow start exit {t.returncode}; the purchase is {it['item']['state']} and the purchase system {'received order ' + order if order else 'received nothing'}")

KERNEL_DSN = "postgres://kernel:kernel@127.0.0.1:15432/kernel"
p = psql(KERNEL_DSN, "select count(*) from items")
row("kernel", "Postgres with the development password", "OPEN" if p.returncode == 0 else "closed",
    f"psql exit {p.returncode}: {p.stdout.strip() or p.stderr.strip()} Items readable. Here Postgres holds the truth, not a copy: "
    "whoever can write it can write any state (not done)")

open(os.path.join(SPIKE, "results/sidedoors.md"), "w").write("\n".join(out) + "\n")
