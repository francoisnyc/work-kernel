"""Test 1: the owner's change, "Purchases over 5,000 also need the CFO's
approval, after finance", applied to a running system on each side.

For each side: a 6,000 purchase is in flight before the change; the change
is checked and put live; a new 6,000 purchase then goes through; and the
in-flight one is followed to its end. On the kernel, a requester also asks
for the old version by name after the change. On Camunda, a deployment with
two typing slips shows what is checked before the change runs.
Writes results/test1-cfo.md.
"""
import os
import subprocess
import tempfile
import time

from bakeoff import SPIKE, camunda, camunda_submit, pli, short

out = ["# Test 1: the CFO change\n",
       f"Generated by scripts/test1-cfo.py on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}.\n"]


def say(line):
    print(line)
    out.append(line)


def k_new(version, amount=6000):
    _, c = pli("ana", "item", "create", "--type", f"purchase@{version}", "--set", f"f_amount={amount}", "--set", "f_vendor=cloudhost",
               "--set", "f_cost_centre=CC-100", "--set", "f_justification=Three servers for the data team")
    i = short(c["item"]["name"])
    pli("ana", "item", "transition", i, "--to", "manager_review", "--wait", "5s")
    return i


def k_through_finance(i):
    pli("bob", "item", "transition", i, "--to", "finance_queue")
    pli("fay", "item", "transition", i, "--to", "finance_review", "--set", "f_claimed_by=user:fay")
    ok, res = pli("fay", "item", "transition", i, "--to", "approved", check=False)
    if ok:
        return res["item"]["state"], "fay approved: approved"
    err = " ".join(str(res).split())[:90]
    _, res = pli("fay", "item", "transition", i, "--to", "cfo_review")
    return res["item"]["state"], f"fay's approve refused ({err}); fay sent it to the CFO: {res['item']['state']}"


# ------------------------------------------------------------- kernel
say("\n## Kernel\n")
before, before2 = k_new(1), k_new(1)
say(f"- In flight before the change: two purchase@1 ({before}, {before2}), 6,000 each, waiting on the manager.")
# Before it runs: the kernel checks the draft (with two typing slips, then
# as written) and explains it in plain language. Nothing is registered yet.
PLI = [f"{SPIKE}/scripts/pli.sh", "--as", "fay"]
v2 = f"{SPIKE}/kernel/types-v2/purchase.v2.yaml"
with tempfile.TemporaryDirectory() as d:
    slip = os.path.join(d, "purchase.v2.yaml")
    open(slip, "w").write(open(v2).read().replace("guard: 'f_amount > 5000'", "guard: 'f_amont > 5000'")
                          .replace("to: cfo_review,     allowed: ['role:finance']", "to: cfo_reveiw,     allowed: ['role:finance']"))
    r1 = subprocess.run(PLI + ["type", "validate", slip], capture_output=True, text=True)
r2 = subprocess.run(PLI + ["type", "validate", v2], capture_output=True, text=True)
r3 = subprocess.run(PLI + ["type", "explain", "--draft", "purchase@2", v2], capture_output=True, text=True)
open(f"{SPIKE}/results/test1-kernel-validate.txt", "w").write(
    "$ pli type validate purchase.v2.yaml   # with f_amont and cfo_reveiw typed by mistake\n"
    + (r1.stdout + r1.stderr).replace(d + "/", "") + f"exit {r1.returncode}\n\n$ pli type validate kernel/types-v2/purchase.v2.yaml\n"
    + r2.stdout + r2.stderr + f"exit {r2.returncode}\n")
open(f"{SPIKE}/results/test1-kernel-explain-v2.txt", "w").write(
    "$ pli type explain --draft purchase@2 kernel/types-v2/purchase.v2.yaml\n" + r3.stdout + r3.stderr)
say(f"- `pli type validate` on the draft with two typing slips: exit {r1.returncode}, {len((r1.stdout + r1.stderr).strip().splitlines())} problems named "
    f"with file, line and a suggested fix; on the draft as written: exit {r2.returncode}, no problems (results/test1-kernel-validate.txt).")
say(f"- `pli type explain --draft purchase@2`: {len(r3.stdout.splitlines())} lines of plain language, nothing registered yet (results/test1-kernel-explain-v2.txt).")
subprocess.run([f"{SPIKE}/scripts/kernel-restart-itemservice.sh", f"{SPIKE}/kernel/types-v2"], check=True, capture_output=True)
_, tl = pli("fay", "type", "list")
say(f"- Item service restarted with kernel/types-v2 (v1 unchanged, v2 added): registered {sorted((t['type_id'], t['version']) for t in tl['types'])}")
new = k_new(2)
state, how = k_through_finance(new)
say(f"- New purchase@2 {new}, 6,000: manager approved; {how}")
ok, res = pli("fay", "item", "transition", new, "--to", "approved", check=False)
say(f"- fay (finance) tries to approve it in cfo_review: {'allowed' if ok else 'refused: ' + ' '.join(str(res).split())[:90]}")
_, ses = pli("prep-bot", "agent", "start", "--scopes", "namespaces/acme", "--powers", "read,create,edit_fields,transition:*,move", "--for", "user:cora")
ok, res = pli("prep-bot", "item", "transition", new, "--to", "approved", session=ses["session"]["id"], check=False)
say(f"- The agent, acting for the CFO with every power, tries to approve it: {'allowed' if ok else 'refused: ' + ' '.join(str(res).split())[:90]}")
_, res = pli("cora", "item", "transition", new, "--to", "approved")
time.sleep(2)
_, res = pli("cora", "item", "get", new)
say(f"- cora (cfo) approves: state `{res['item']['state']}`, order `{res['item']['fields'].get('f_order_id')}`")
state, how = k_through_finance(before)
say(f"- The in-flight purchase@1 {before}: {how} (it keeps the rules it was created under, unless migrated)")
# Since track 1, item 6, step 2 an administrator can migrate a purchase in flight to the new version, once the kernel has checked that it fits.
_, dry = pli("ivy", "item", "migrate", before2, "--to", "purchase@2", "--dry-run")
ok, res = pli("ivy", "item", "migrate", before2, "--to", "purchase@2", check=False)
if ok:
    state, how = k_through_finance(before2)
    say(f"- The other in-flight purchase {before2}, migrated by an administrator to purchase@2 (the dry run found {len(dry.get('problems', []))} problems; "
        f"it is now {res['item']['type'].split('/types/')[1].replace('/versions/', '@')}): {how}: the change reaches a request already in flight.")
else:
    say(f"- The other in-flight purchase {before2}: the migrate was refused: " + " ".join(str(res).split())[:200])
# Since track 1, item 6, step 1 the kernel refuses this create; the row records the refusal (it used to run the purchase to its end).
ok, res = pli("ana", "item", "create", "--type", "purchase@1", "--set", "f_amount=6000", "--set", "f_vendor=cloudhost",
              "--set", "f_cost_centre=CC-100", "--set", "f_justification=Three servers for the data team", check=False)
say("- After the change, ana asks for the OLD version by name (purchase@1), 6,000: "
    + ("created: the kernel lets a creator pick any registered version, and the CFO can be skipped." if ok
       else "refused: " + " ".join(str(res).split())[:200]))

# ------------------------------------------------------------- camunda
say("\n## Camunda\n")


def c_new(amount=6000):
    _, pi = camunda_submit("ana", "purchase-submitted", {"amount": amount, "vendor": "cloudhost", "costCentre": "CC-100",
                                                         "justification": "Three servers for the data team", "requester": "ana"})
    return pi


def c_task(pi, element=None):
    for _ in range(80):
        f = {"processInstanceKey": str(pi), "state": "CREATED"}
        if element:
            f["elementId"] = element
        _, r = camunda("demo", "POST", "/v2/user-tasks/search", {"filter": f})
        if r.get("items"):
            return r["items"][0]
        time.sleep(0.5)
    return None


def c_do(user, t, var):
    camunda(user, "POST", f"/v2/user-tasks/{t['userTaskKey']}/assignment", {"assignee": user, "action": "claim", "allowOverride": False})
    return camunda(user, "POST", f"/v2/user-tasks/{t['userTaskKey']}/completion", {"variables": {var: True}})[0]


def c_after_finance(pi):
    c_do("bob", c_task(pi, "manager_decision"), "managerApproved")
    c_do("fay", c_task(pi, "finance_decision"), "financeApproved")
    time.sleep(2)
    t = c_task(pi)
    if t:
        return t
    _, v = camunda("demo", "POST", "/v2/variables/search", {"filter": {"processInstanceKey": str(pi), "name": "orderId"}})
    return {"elementId": "(ended) orderId=" + (v["items"][0]["value"] if v.get("items") else "none")}


before = c_new()
before2 = c_new()
_, pi = camunda("demo", "GET", f"/v2/process-instances/{before}")
say(f"- In flight before the change: two instances of purchase version {pi.get('processDefinitionVersion')} ({before}, {before2}), 6,000 each.")
# The same two slips as on the kernel side: a misspelled element and a
# misspelled variable; then the variable alone.
src = open(f"{SPIKE}/camunda/purchase-cfo.bpmn").read()
slips = {"an element ID and a variable misspelled": src.replace('targetRef="cfo_decision"', 'targetRef="cfo_decison"')
         .replace("amount &gt; 5000", "amont &gt; 5000"),
         "a variable misspelled (amont)": src.replace("amount &gt; 5000", "amont &gt; 5000")}
with tempfile.TemporaryDirectory() as d:
    for what, text in slips.items():
        path = os.path.join(d, "purchase.bpmn")
        open(path, "w").write(text)
        r = subprocess.run([f"{SPIKE}/scripts/camunda-deploy.sh", path], capture_output=True, text=True)
        say(f"- Deploy with {what}: `{' '.join((r.stdout + r.stderr).split())[:500]}`")
r = subprocess.run([f"{SPIKE}/scripts/camunda-deploy.sh", f"{SPIKE}/camunda/purchase-cfo.bpmn"], capture_output=True, text=True)
say(f"- Deploy camunda/purchase-cfo.bpmn: `{' '.join(r.stdout.split())}`")
new = c_new()
_, pi = camunda("demo", "GET", f"/v2/process-instances/{new}")
t = c_after_finance(new)
say(f"- New purchase (the start message now starts version {pi.get('processDefinitionVersion')}), 6,000: manager and finance approved; now at `{t['elementId']}` for {t.get('candidateGroups')}")
st0 = camunda("prep-bot", "POST", f"/v2/user-tasks/{t['userTaskKey']}/completion", {"variables": {"cfoApproved": True}})[0]
say(f"- The agent's user tries to complete the CFO task: HTTP {st0}")
st = c_do("fay", t, "cfoApproved") if t.get("userTaskKey") else None
say(f"- fay (finance, not cfo) tries to claim and complete the CFO task: HTTP {st}")
st = c_do("cora", t, "cfoApproved")
time.sleep(3)
_, v = camunda("demo", "POST", "/v2/variables/search", {"filter": {"processInstanceKey": str(new), "name": "orderId"}})
say(f"- cora (cfo group) approves: HTTP {st}; orderId {v['items'][0]['value'] if v.get('items') else 'none'}")
t = c_after_finance(before)
say(f"- The in-flight instance {before}: after finance, at `{t['elementId']}` (it keeps the version it started on, unless migrated)")
# Camunda can move a running instance to the new version (migration).
c_task(before2, "manager_decision")
st, res = camunda("demo", "POST", f"/v2/process-instances/{before2}/migration", {
    "targetProcessDefinitionKey": str(pi.get("processDefinitionKey")),
    "mappingInstructions": [{"sourceElementId": "manager_decision", "targetElementId": "manager_decision"}]})
time.sleep(2)
t = c_after_finance(before2) if 200 <= st < 300 else {"elementId": "(not migrated)"}
say(f"- The other in-flight instance {before2}, migrated by an admin to the new version (HTTP {st}{'' if 200 <= st < 300 else ' ' + str(res)[:200]}): "
    f"after finance, at `{t['elementId']}`: the change reaches a request already in flight.")
say("- A requester cannot pick the old version: requests start by message, and a message starts the latest deployed version. "
    "(With an ordinary start, the API accepts a version number.)")
open(os.path.join(SPIKE, "results/test1-cfo.md"), "w").write("\n".join(out) + "\n")
