"""The scenario's other two paths, on both sides: a 300 purchase the manager
alone approves (the order is placed), and a 2,500 purchase finance rejects
(the requester is told, the reason is kept). Writes results/test0-paths.md.
"""
import json
import time
import urllib.request

from bakeoff import SPIKE, camunda, camunda_submit, pli, short

out = ["# The scenario's other paths: small purchase, and a rejection\n",
       f"Generated by scripts/test0-paths.py on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}.\n"]


def mails(item):
    with urllib.request.urlopen(f"http://127.0.0.1:18085/messages?item={item}") as r:
        d = json.load(r)
    return [(m["to"], m["template"]) for m in (d.get("messages", d) if isinstance(d, dict) else d)]


def k_new(amount):
    _, c = pli("ana", "item", "create", "--type", "purchase@1", "--set", f"f_amount={amount}", "--set", "f_vendor=officeco",
               "--set", "f_cost_centre=CC-200", "--set", "f_justification=Whiteboards")
    i = short(c["item"]["name"])
    pli("ana", "item", "transition", i, "--to", "manager_review", "--wait", "5s")
    return i


out.append("\n## Kernel\n")
i = k_new(300)
pli("bob", "item", "transition", i, "--to", "approved")
time.sleep(3)
_, it = pli("ana", "item", "get", i)
out.append(f"- 300: bob approves: state `{it['item']['state']}`, order `{it['item']['fields'].get('f_order_id')}` (finance never involved)")
i = k_new(2500)
pli("bob", "item", "transition", i, "--to", "finance_queue")
pli("gus", "item", "transition", i, "--to", "finance_review", "--set", "f_claimed_by=user:gus")
ok, err = pli("gus", "item", "transition", i, "--to", "rejected", check=False)
out.append(f"- 2,500: gus rejects without a reason: {'allowed' if ok else 'refused: ' + ' '.join(str(err).split())[:100]}")
pli("gus", "item", "transition", i, "--to", "rejected", "--set", "f_reason=Over the cost centre's budget this quarter")
time.sleep(3)
_, it = pli("ana", "item", "get", i)
out.append(f"- gus rejects with a reason: state `{it['item']['state']}`, reason on the Item: \"{it['item']['fields'].get('f_reason')}\"; email stub: {mails(i)}")


def c_task(pi, el):
    for _ in range(80):
        _, r = camunda("demo", "POST", "/v2/user-tasks/search", {"filter": {"processInstanceKey": str(pi), "elementId": el, "state": "CREATED"}})
        if r.get("items"):
            return r["items"][0]
        time.sleep(0.5)


def c_do(user, pi, el, variables):
    t = c_task(pi, el)
    camunda(user, "POST", f"/v2/user-tasks/{t['userTaskKey']}/assignment", {"assignee": user, "action": "claim", "allowOverride": False})
    return camunda(user, "POST", f"/v2/user-tasks/{t['userTaskKey']}/completion", {"variables": variables})[0]


def c_var(pi, name):
    _, v = camunda("demo", "POST", "/v2/variables/search", {"filter": {"processInstanceKey": str(pi), "name": name}})
    return v["items"][0]["value"] if v.get("items") else None


out.append("\n## Camunda\n")
v = {"amount": 300, "vendor": "officeco", "costCentre": "CC-200", "justification": "Whiteboards", "requester": "ana"}
_, pi = camunda_submit("ana", "purchase-submitted", v)
c_do("bob", pi, "manager_decision", {"managerApproved": True})
time.sleep(3)
_, p = camunda("demo", "GET", f"/v2/process-instances/{pi}")
out.append(f"- 300: bob approves: instance `{p.get('state')}`, orderId {c_var(pi, 'orderId')} (finance never involved)")
ref = "bakeoff-reject-" + str(int(time.time()))
_, pi = camunda_submit("ana", "purchase-submitted", dict(v, amount=2500, requestRef=ref))
c_do("bob", pi, "manager_decision", {"managerApproved": True})
c_do("gus", pi, "finance_decision", {"financeApproved": False, "reason": "Over the cost centre's budget this quarter"})
time.sleep(3)
_, p = camunda("demo", "GET", f"/v2/process-instances/{pi}")
out.append(f"- 2,500: gus rejects with a reason: instance `{p.get('state')}`, variable reason {c_var(pi, 'reason')}; email stub: {mails(ref)}")
_, pi = camunda_submit("ana", "purchase-submitted", dict(v, amount=2500))
c_do("bob", pi, "manager_decision", {"managerApproved": True})
st = c_do("gus", pi, "finance_decision", {"financeApproved": False})
time.sleep(3)
_, p = camunda("demo", "GET", f"/v2/process-instances/{pi}")
out.append(f"- 2,500: gus rejects without a reason: HTTP {st}, instance `{p.get('state')}`, reason {c_var(pi, 'reason')} "
           f"({'accepted: the model has no rule for it; a form or a task listener would add one' if st == 204 else 'refused'})")
open(f"{SPIKE}/results/test0-paths.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
