#!/usr/bin/env bash
# Test 4: a memory snapshot of each side (the shared stubs are on neither).
#   scripts/test4-footprint.sh LABEL   appends to results/test4-footprint.md
cd "$(dirname "$0")/.."
LABEL=${1:-snapshot}
OUT=results/test4-footprint.md
[ -f "$OUT" ] || printf '# Test 4: footprint\n\nGenerated by scripts/test4-footprint.sh. Memory as docker stats (containers) and ps RSS (the kernel programs, which run on the host).\n' > "$OUT"
{
  echo; echo "## $LABEL ($(date -u '+%Y-%m-%d %H:%M UTC'))"; echo
  echo "| Side | Part | Memory | CPU |"; echo "|---|---|---|---|"
  docker stats --no-stream --format '{{.Name}}|{{.MemUsage}}|{{.CPUPerc}}' | sort | while IFS='|' read -r n m c; do
    case $n in *kernel*) s=kernel;; *orchestration*|*connectors*) s=camunda;; *) continue;; esac
    echo "| $s | container ${n#bakeoff-} | ${m%% /*} | $c |"
  done
  for p in itemservice relay worker; do
    [ -f .run/$p.pid ] || continue
    rss=$(ps -o rss= -p "$(cat .run/$p.pid)" 2>/dev/null) || continue
    echo "| kernel | process $p | $((rss / 1024))MiB | |"
  done
  echo; echo "Images: $(docker images --format '{{.Repository}}:{{.Tag}} {{.Size}}' | grep -E 'camunda|postgres:17|temporal' | sort | tr '\n' ';' | sed 's/;/; /g')"
} >> "$OUT"
tail -15 "$OUT"
