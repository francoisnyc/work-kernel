"""Test 3: one inbox. Seeds the same six requests on both sides, then prints
fay's inbox on each (fay is in finance and owns the "ledger" system).
Expected in fay's inbox: two purchases in the finance queue or claimed by
her, the one gus claimed (her team's, but not hers to decide), and the
ledger access request. Not expected: the payroll request (olaf's) and the
small purchase waiting on bob. Writes results/test3-inbox.md.
"""
import subprocess
import time

from bakeoff import SPIKE, camunda, camunda_submit, pli, short


def k_purchase(amount, vendor, why, claim=None):
    _, c = pli("ana", "item", "create", "--type", "purchase@1", "--set", f"f_amount={amount}", "--set", f"f_vendor={vendor}",
               "--set", "f_cost_centre=CC-100", "--set", f"f_justification={why}")
    i = short(c["item"]["name"])
    pli("ana", "item", "transition", i, "--to", "manager_review", "--wait", "5s")
    if amount >= 1000:
        pli("bob", "item", "transition", i, "--to", "finance_queue")
    if claim:
        pli(claim, "item", "transition", i, "--to", "finance_review", "--set", f"f_claimed_by=user:{claim}")


def k_access(system, role, why):
    _, res = pli("ivy", "item", "search", "--type", "namespaces/acme/types/system", "--where", f"f_name={system}")
    if res.get("items"):
        s = short(res["items"][0]["name"])
    else:
        owner = {"payroll": "olaf", "ledger": "fay"}[system]
        _, c = pli("ivy", "item", "create", "--type", "system@1", "--set", f"f_name={system}", "--set", f"f_owner=user:{owner}")
        s = short(c["item"]["name"])
    _, c = pli("ana", "item", "create", "--type", "system_access@1", "--in", s, "--set", f"f_role={role}", "--set", f"f_justification={why}")
    pli("ana", "item", "transition", short(c["item"]["name"]), "--to", "owner_review")


def c_task(pi, element):
    for _ in range(80):
        _, r = camunda("demo", "POST", "/v2/user-tasks/search", {"filter": {"processInstanceKey": str(pi), "elementId": element, "state": "CREATED"}})
        if r.get("items"):
            return r["items"][0]
        time.sleep(0.5)
    raise RuntimeError(element)


def c_purchase(amount, vendor, why, claim=None):
    _, pi = camunda_submit("ana", "purchase-submitted", {"amount": amount, "vendor": vendor, "costCentre": "CC-100",
                                                         "justification": why, "requester": "ana"})
    t = c_task(pi, "manager_decision")
    if amount < 1000:
        return
    camunda("bob", "POST", f"/v2/user-tasks/{t['userTaskKey']}/assignment", {"assignee": "bob", "action": "claim", "allowOverride": False})
    camunda("bob", "POST", f"/v2/user-tasks/{t['userTaskKey']}/completion", {"variables": {"managerApproved": True}})
    t = c_task(pi, "finance_decision")
    if claim:
        camunda(claim, "POST", f"/v2/user-tasks/{t['userTaskKey']}/assignment", {"assignee": claim, "action": "claim", "allowOverride": False})


def c_access(system, role, why):
    _, pi = camunda_submit("ana", "access-requested", {"system": system, "role": role, "justification": why, "requester": "ana"})
    c_task(pi, "owner_decision")


SEED = [("purchase", 2500, "officeco", "Laptops for two new hires", None),
        ("purchase", 4000, "shadyparts", "Spare parts, urgent", "fay"),
        ("purchase", 1800, "cloudhost", "Hosting for the test cluster", "gus"),
        ("purchase", 300, "officeco", "Desk lamps", None),
        ("access", "ledger", "admin", "Month-end close"),
        ("access", "payroll", "viewer", "Audit sample")]
for s in SEED:
    if s[0] == "purchase":
        k_purchase(*s[1:]); c_purchase(*s[1:])
    else:
        k_access(*s[1:]); c_access(*s[1:])
subprocess.run(["python3", f"{SPIKE}/scripts/kernel-agent.py"], capture_output=True)
time.sleep(2)
k = subprocess.run(["python3", f"{SPIKE}/scripts/kernel-inbox.py", "fay"], capture_output=True, text=True).stdout
c = subprocess.run(["python3", f"{SPIKE}/scripts/camunda-inbox.py", "fay"], capture_output=True, text=True).stdout
text = (f"# Test 3: one inbox (fay: finance team, owner of the ledger system)\n\nGenerated by scripts/test3-inbox.py on "
        f"{time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}, on fresh stacks.\n\nSeeded on both sides: " +
        "; ".join(", ".join(str(x) for x in s if x) for s in SEED) +
        f"\n\n## Kernel (scripts/kernel-inbox.py, built in the spike)\n\n```\n{k}```\n\n## Camunda (the Tasklist API, scripts/camunda-inbox.py)\n\n```\n{c}```\n")
open(f"{SPIKE}/results/test3-inbox.md", "w").write(text)
print(text)

# The claim: can fay decide the purchase gus claimed?
extra = ["\n## Does a claim hold? fay tries to approve the purchase gus claimed\n"]
_, res = pli("fay", "item", "search", "--type", "namespaces/acme/types/purchase", "--where", "f_claimed_by=user:gus")
ok, out_ = pli("fay", "item", "transition", short(res["items"][0]["name"]), "--to", "approved", check=False)
extra.append(f"- Kernel: {'allowed: the claim is only a field, any finance member decides' if ok else 'refused: ' + str(out_)}")
_, r = camunda("demo", "POST", "/v2/user-tasks/search", {"filter": {"assignee": "gus", "state": "CREATED"}})
st, body = camunda("fay", "POST", f"/v2/user-tasks/{r['items'][0]['userTaskKey']}/completion", {"variables": {"financeApproved": True}})
extra.append(f"- Camunda (task-worker tightened in camunda-setup.sh): HTTP {st} {' '.join(str(body.get('detail', '') if isinstance(body, dict) else body).split())[:160]}")
open(f"{SPIKE}/results/test3-inbox.md", "a").write("\n".join(extra) + "\n")
print("\n".join(extra))
