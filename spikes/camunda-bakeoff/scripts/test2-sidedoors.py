"""Test 2c (added after the review): side doors. Not the agent's credentials:
what answers on each side's local ports with no credentials, or with the
development defaults, and whether it leads to an unapproved order.

A compromised agent that runs on the same machine or network as the system
reaches these ports. Writes results/test2-sidedoors.md.
"""
import json
import subprocess
import time
import urllib.error
import urllib.request

from bakeoff import SPIKE, camunda, pli, short

out = ["# Test 2c: side doors (no credentials, or the development defaults)\n",
       f"Generated by scripts/test2-sidedoors.py on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}.\n",
       "| Side | Door | Result | Evidence |", "|---|---|---|---|"]


def row(side, door, bad, evidence, label=None):
    line = f"| {side} | {door} | {label or ('OPEN' if bad else 'closed')} | {' '.join(str(evidence).split())[:260]} |"
    print(line)
    out.append(line)


def http(url, method="GET", body=None):
    req = urllib.request.Request(url, method=method, data=None if body is None else json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            return r.status, r.read()[:200].decode(errors="replace")
    except urllib.error.HTTPError as e:
        return e.code, e.read()[:200].decode(errors="replace")
    except Exception as e:  # connection refused and the like
        return 0, str(e)


