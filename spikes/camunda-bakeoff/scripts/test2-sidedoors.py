pli("ana", "item", "transition", i, "--to", "manager_review", "--wait", "5s")
payload = {"ItemID": i, "Carried": {"TypeID": "purchase", "TypeVersion": 1, "State": "approved", "LastAppliedSeq": 999,
                                    "EnteredSeq": 3, "PendingActions": [{"HookID": "place_order", "CauseSeq": 3}]}}
r = subprocess.run(["docker", "exec", "bakeoff-kernel-temporal-1", "temporal", "workflow", "start", "--address", "localhost:7233",
                    "--type", "item", "--task-queue", "items", "--workflow-id", f"sidedoor-{int(time.time())}",
                    "--input", json.dumps(payload)], capture_output=True, text=True)
