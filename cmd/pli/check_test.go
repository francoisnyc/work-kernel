// Tests for pli check PATH... (pli check, PR 1): it reads Type files or
// folders, as type validate does, and calls no server, so it needs no --as.
// It prints the report's text, or with --json the report. Exit 0 when no
// finding is an ERROR (warnings print but pass), 1 when one is, 2 on a
// usage error or a Type that does not load.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"strings"
	"testing"
)

// checkCmd runs pli with no --as and no server.
func checkCmd(t *testing.T, args ...string) result {
	t.Helper()
	var out, errb bytes.Buffer
	code := run(context.Background(), append([]string{"--server", "http://127.0.0.1:1", "check"}, args...), &out, &errb)
	return result{code: code, stdout: out.String(), stderr: errb.String()}
}

// Warnings only (the staff-role bake-off: an agent holding finance
// decides; the access request stuck if the requester holds staff):
// printed, exit 0.
func TestCheckWarningsExitZero(t *testing.T) {
	r := checkCmd(t, "../../spikes/temporal-bakeoff/kernel-staff-role/types")
	if r.code != exitOK {
		t.Fatalf("exit %d, want 0; stderr %q", r.code, r.stderr)
	}
	for _, want := range []string{"purchase@1\n", "AGENT_DECIDES WARNING transitions[6]", "Not checked: who reads it", "0 errors, 2 warnings.\n"} {
		if !strings.Contains(r.stdout, want) {
			t.Errorf("stdout lacks %q:\n%s", want, r.stdout)
		}
	}
}

// An ERROR (the access request for no system): exit 1.
func TestCheckErrorExitOne(t *testing.T) {
	r := checkCmd(t, "../../spikes/camunda-bakeoff/kernel/types")
	if r.code != exitAPI {
		t.Fatalf("exit %d, want 1; stdout %q stderr %q", r.code, r.stdout, r.stderr)
	}
	if !strings.Contains(r.stdout, "STUCK_STATE ERROR states[1]: It can stay in owner_review for ever") {
		t.Errorf("stdout:\n%s", r.stdout)
	}
}

// A file works as a folder does, and --json prints the report.
func TestCheckJSONOfAFile(t *testing.T) {
	r := checkCmd(t, "--json", "../../spikes/camunda-bakeoff/kernel/types/purchase.v1.yaml")
	if r.code != exitOK {
		t.Fatalf("exit %d, want 0; stderr %q", r.code, r.stderr)
	}
	var doc struct {
		Findings []struct {
			Type, Code, Severity, Path string
			Version                    int
		} `json:"findings"`
		NotChecked []string `json:"not_checked"`
	}
	if err := json.Unmarshal([]byte(r.stdout), &doc); err != nil {
		t.Fatalf("stdout is not JSON (%v): %q", err, r.stdout)
	}
	// PR 2: the draft's colleague finding comes first (warnings by path).
	if len(doc.Findings) != 2 || doc.Findings[0].Code != "COLLEAGUE_EDITS_DRAFT" || doc.Findings[0].Path != "states[0]" ||
		doc.Findings[1].Code != "AGENT_DECIDES" || doc.Findings[1].Path != "transitions[6]" ||
		doc.Findings[1].Type != "purchase" || doc.Findings[1].Version != 1 || len(doc.NotChecked) == 0 {
		t.Errorf("JSON: %s", r.stdout)
	}
}

// No PATH, or a PATH that is not there: a usage error, exit 2.
func TestCheckUsage(t *testing.T) {
	for _, args := range [][]string{{}, {"--json"}, {"no/such/folder"}} {
		r := checkCmd(t, args...)
		if r.code != exitUsage || r.stderr == "" {
			t.Errorf("pli check %q: exit %d stderr %q, want 2 and a message", args, r.code, r.stderr)
		}
	}
}

// A Type that does not load: its problems on stderr, as type validate
// prints them, nothing checked, exit 2.
func TestCheckTypeThatDoesNotLoad(t *testing.T) {
	dir := tree(t, map[string]string{"bad.v1.yaml": "id: bad\nversion: 1\ninitial_state: nowhere\nstates:\n  - {id: open, category: todo}\n"})
	r := checkCmd(t, dir)
	if r.code != exitUsage {
		t.Fatalf("exit %d, want 2; stdout %q stderr %q", r.code, r.stdout, r.stderr)
	}
	if !strings.Contains(r.stderr, "bad.v1.yaml") || !strings.Contains(r.stderr, "typedef bad v1") {
		t.Errorf("stderr does not name the file and the Type: %q", r.stderr)
	}
	if r.stdout != "" {
		t.Errorf("stdout %q, want nothing", r.stdout)
	}
}

// pli check PR 3: --stories prints each finding's witness run under its
// witness; the text without it is as before. --json always gives each
// finding with a witness its story.
func TestCheckStories(t *testing.T) {
	dir := "../../spikes/camunda-bakeoff/kernel/types"
	r := checkCmd(t, "--stories", dir)
	if r.code != exitAPI {
		t.Fatalf("exit %d, want 1 (the stuck access request); stderr %q", r.code, r.stderr)
	}
	for _, want := range []string{
		"    5. An agent holding finance moves it from finance_review to approved.\n    Witness run:\n" +
			"      story: \"witness run: purchase@1 AGENT_DECIDES transitions[6]\"\n" +
			"      author: generated by pli check from its witness; no person wrote or approved it\n",
		"      expect: []\n",
	} {
		if !strings.Contains(r.stdout, want) {
			t.Errorf("stdout lacks %q:\n%s", want, r.stdout)
		}
	}
	if plain := checkCmd(t, dir); strings.Contains(plain.stdout, "Witness run") {
		t.Errorf("without --stories the text prints witness runs:\n%s", plain.stdout)
	}
	// Both flags: --json wins, as it holds the stories too.
	for _, args := range [][]string{{"--json", dir}, {"--json", "--stories", dir}} {
		r := checkCmd(t, args...)
		var doc struct {
			Findings []struct {
				Code, Path, Story string
				Witness           []any
			} `json:"findings"`
		}
		if err := json.Unmarshal([]byte(r.stdout), &doc); err != nil {
			t.Fatalf("pli check %q: stdout is not JSON (%v): %q", args, err, r.stdout)
		}
		if len(doc.Findings) == 0 {
			t.Fatalf("pli check %q: no findings: %s", args, r.stdout)
		}
		for _, f := range doc.Findings {
			if len(f.Witness) > 0 && !strings.HasPrefix(f.Story, "story: \"witness run: ") {
				t.Errorf("pli check %q: %s %s has no story: %q", args, f.Code, f.Path, f.Story)
			}
		}
	}
}
